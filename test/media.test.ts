      const upload = await service.authorizeUpload(editor, { type: 'image', bytes: validPng().length });
      assert.equal(upload.status, 201);
      if (upload.status !== 201) return;
      if (failure !== 'missing') storage.objects.set('cms-media-private/' + upload.data.privateKey, validPng());
      storage.failRead = failure === 'read';
      repository.failFinalize = failure === 'rpc';
      assert.equal((await service.finalizeUpload(editor, upload.data.asset.id)).status, failure === 'missing' ? 400 : 502);
      assert.equal((await repository.getAsset(upload.data.asset.id))?.status, 'uploading');
      storage.failRead = false;
      repository.failFinalize = false;
      storage.objects.set('cms-media-private/' + upload.data.privateKey, validPng());
      assert.equal((await service.finalizeUpload(editor, upload.data.asset.id)).status, 200);
