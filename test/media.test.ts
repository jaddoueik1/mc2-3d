function validGlb(document: Record<string, unknown> = { asset: { version: '2.0' }, buffers: [], images: [] }, bin?: Uint8Array): Uint8Array {
  const json = new TextEncoder().encode(JSON.stringify(document));
  const padded = new Uint8Array(Math.ceil(json.length / 4) * 4);
  padded.set(json);
  padded.fill(0x20, json.length);
  const bytes = new Uint8Array(12 + 8 + padded.length + (bin ? 8 + Math.ceil(bin.length / 4) * 4 : 0));
  const view = new DataView(bytes.buffer);
  view.setUint32(0, 0x46546c67, true);
  view.setUint32(4, 2, true);
  view.setUint32(8, bytes.length, true);
  view.setUint32(12, padded.length, true);
  view.setUint32(16, 0x4e4f534a, true);
  bytes.set(padded, 20);
  if (bin) {
    const offset = 20 + padded.length;
    view.setUint32(offset, Math.ceil(bin.length / 4) * 4, true);
    view.setUint32(offset + 4, 0x004e4942, true);
    bytes.set(bin, offset + 8);
  }
  return bytes;
}

