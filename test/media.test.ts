function imageFixture(format: keyof typeof imageFixtures): Uint8Array {
  return Uint8Array.from(globalThis.atob(imageFixtures[format]), (part) => part.charCodeAt(0));
}

function corruptImage(format: keyof typeof imageFixtures): Uint8Array {
  const bytes = imageFixture(format);
  if (format === 'jpeg') bytes[6] = 0xff; // Invalid quantization table, intact markers/lengths/frame/EOI.
  if (format === 'webp') bytes.fill(0xff, 30); // Intact RIFF/VP8 dimensions, broken compressed pixels.
  if (format === 'png') {
    const view = new DataView(bytes.buffer);
    for (let offset = 8; offset < bytes.length;) {
      const length = view.getUint32(offset);
      if (new TextDecoder().decode(bytes.slice(offset + 4, offset + 8)) === 'IDAT') {
        bytes.fill(0, offset + 8, offset + 8 + length);
        let crc = 0xffffffff;
        for (const byte of bytes.slice(offset + 4, offset + 8 + length)) {
          crc ^= byte;
          for (let bit = 0; bit < 8; bit++) crc = (crc >>> 1) ^ (crc & 1 ? 0xedb88320 : 0);
        }
        view.setUint32(offset + 8 + length, (crc ^ 0xffffffff) >>> 0);
      }
      offset += length + 12;
    }
  }
  return bytes;
}

class MemoryRepository implements MediaRepository {
  readonly assets = new Map<string, MediaAsset>();
  readonly published = new Set<string>();
  readonly grants = new Map<string, { ownerId: string; bucket: string; key: string; expiresAt: string; finalized: boolean }>();
  failFinalize = false;
  clock = '2026-09-15T00:00:00.000Z';

  async createUploading(asset: MediaAsset): Promise<void> {
    this.assets.set(asset.id, asset);
  }

  async createUploadGrant(asset: MediaAsset): Promise<{ expiresAt: string }> {
    const expiresAt = new Date(Date.parse(this.clock) + 600_000).toISOString();
    this.grants.set(asset.id, { ownerId: asset.ownerId, bucket: asset.privateBucket, key: asset.privateKey, expiresAt, finalized: false });
    return { expiresAt };
  }

  async getAsset(id: string): Promise<MediaAsset | null> {
    return this.assets.get(id) ?? null;
  }

  async finalizeValidatedAsset(asset: MediaAsset, patch: { byteSize: number; mimeType: string; sha256: string }): Promise<MediaAsset | null> {
    if (this.failFinalize) throw new Error('RPC failed');
    const grant = this.grants.get(asset.id);
    if (!grant || grant.finalized || grant.ownerId !== asset.ownerId || grant.bucket !== asset.privateBucket || grant.key !== asset.privateKey || grant.expiresAt <= this.clock) return null;
    const ready: MediaAsset = { ...asset, ...patch, status: 'ready', finalizedAt: this.clock };
    grant.finalized = true;
    this.assets.set(asset.id, ready);
    return ready;
  }

  async setPublicKey(id: string, publicKey: string): Promise<void> {
    const asset = this.assets.get(id);
    if (!asset) throw new Error('missing asset');
    this.assets.set(id, { ...asset, publicKey });
  }

  async findPublishedReadyAsset(id: string): Promise<MediaAsset | null> {
    const asset = this.assets.get(id);
    return asset && asset.status === 'ready' && asset.publicKey && this.published.has(id) ? asset : null;
  }
}

class MemoryStorage implements MediaStorage {
  readonly objects = new Map<string, Uint8Array>();
  readonly copied: Array<{ sourceKey: string; destinationKey: string }> = [];
  failCopy = false;
  failRead = false;

  async getObject(bucket: string, key: string): Promise<Uint8Array | null> {
    if (this.failRead) throw new Error('Storage read failed');
    return this.objects.get(bucket + '/' + key) ?? null;
  }

  async createSignedUrl(bucket: string, key: string, expiresInSeconds: number): Promise<string> {
    return 'https://preview.example.test/' + bucket + '/' + key + '?ttl=' + expiresInSeconds;
  }

  async copyObject(
    sourceBucket: string,
    sourceKey: string,
    destinationBucket: string,
    destinationKey: string,
  ): Promise<void> {
    if (this.failCopy) throw new Error('copy failed');
    const bytes = this.objects.get(sourceBucket + '/' + sourceKey);
    if (!bytes) throw new Error('missing source');
    this.objects.set(destinationBucket + '/' + destinationKey, bytes);
    this.copied.push({ sourceKey, destinationKey });
  }

  publicUrl(bucket: string, key: string): string {
    return 'https://public.example.test/' + bucket + '/' + key;
  }
}

